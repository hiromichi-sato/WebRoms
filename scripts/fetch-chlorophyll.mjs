import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { REGIONS } from './fetch-climatology.mjs';
const url = 'https://oceanwatch.pifsc.noaa.gov/erddap/griddap/aqua_chla_climatology_2018_0.json?chlor_a[0:24:4319][0:24:8639]';
await mkdir(new URL('../.tools/', import.meta.url), { recursive: true });
const cache = new URL('../.tools/chlorophyll-climatology.json', import.meta.url);
let raw;
try { raw = await readFile(cache, 'utf8'); } catch {
  const response = await fetch(url, { signal: AbortSignal.timeout(120000) });
  if (!response.ok) throw new Error(`NOAA HTTP ${response.status}`);
  raw = await response.text(); JSON.parse(raw); await writeFile(cache, raw);
}
const table = JSON.parse(raw).table;
const regions = REGIONS.map(region => {
  let sum = 0, weight = 0, count = 0;
  for (const [lat, lon, chl] of table.rows) if (lat >= region.south && lat < region.north && lon >= region.west && lon < region.east && Number.isFinite(chl) && chl > 0) {
    const w = Math.cos(lat * Math.PI / 180); sum += chl * w; weight += w; count++;
  }
  if (!count) throw new Error(`Missing chlorophyll: ${region.id}`);
  return { id: region.id, chlorophyllMgM3: sum / weight, count };
});
const data = { product: 'NASA MODIS Aqua, NOAA OceanWatch distribution', period: '2003-01 to 2019-02 cumulative mean (not a seasonal climatology)', url, sourcePage: 'https://oceanwatch.pifsc.noaa.gov/erddap/griddap/aqua_chla_climatology_2018_0.html', sha256: createHash('sha256').update(raw).digest('hex'), method: '1 degree subsample; cosine latitude weighted regional mean of finite positive cells; surface chlorophyll only', regions };
await writeFile(new URL('../src/data/chlorophyll.js', import.meta.url), '// Generated by scripts/fetch-chlorophyll.mjs; do not hand-edit observations.\nexport const CHLOROPHYLL = ' + JSON.stringify(data, null, 2) + ';\n');
