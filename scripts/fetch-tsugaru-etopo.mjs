import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';

// Keep the full 15-arc-second coastline grid for the supplied Tsugaru samples.
const url = 'https://oceanwatch.pifsc.noaa.gov/erddap/griddap/ETOPO_2022_v1_15s.json?z[31199:1:31681][33359:1:34081]';
const cache = new URL('../.tools/terrain/tsugaru-15s-padded.json', import.meta.url);
await mkdir(new URL('./', cache), { recursive: true });
let bytes;
try { bytes = await readFile(cache); }
catch {
  const response = await fetch(url, { signal: AbortSignal.timeout(240000) });
  if (!response.ok) throw new Error(`NOAA ETOPO: HTTP ${response.status}`);
  bytes = Buffer.from(await response.arrayBuffer());
  JSON.parse(bytes); await writeFile(cache, bytes);
}
const table = JSON.parse(bytes).table;
if (JSON.stringify(table?.columnNames) !== JSON.stringify(['latitude', 'longitude', 'z'])) throw new Error('Unexpected NOAA columns');
const xs = [...new Set(table.rows.map(row => row[1]))].sort((a,b) => a-b), ys = [...new Set(table.rows.map(row => row[0]))].sort((a,b) => a-b);
if (xs.length !== 723 || ys.length !== 483 || table.rows.length !== xs.length * ys.length) throw new Error('Incomplete Tsugaru 15-second grid');
const xi = new Map(xs.map((x,i) => [x,i])), yi = new Map(ys.map((y,i) => [y,i]));
const elevation = new Array(xs.length * ys.length);
for (const [lat,lon,z] of table.rows) {
  if (!Number.isFinite(z) || Math.abs(z) > 20000) throw new Error('Missing or invalid ETOPO elevation');
  elevation[yi.get(lat) * xs.length + xi.get(lon)] = z;
}
const tile = { id: 'tsugaru-15s', width: xs.length, height: ys.length, bounds: { west: xs[0], east: xs.at(-1), south: ys[0], north: ys.at(-1) }, resolutionArcSeconds: 15, source: 'NOAA ETOPO 2022', sourceUrl: url, sourceSha256: createHash('sha256').update(bytes).digest('hex'), elevation };
await writeFile(new URL('../src/data/terrain-tsugaru-etopo2022.js', import.meta.url), '// Generated by scripts/fetch-tsugaru-etopo.mjs. NOAA ETOPO 2022, unthinned 15-arc-second regional grid.\nexport const TSUGARU_ETOPO = ' + JSON.stringify(tile) + ';\n');
console.log(`Tsugaru ETOPO: ${tile.width}x${tile.height}, bounds ${JSON.stringify(tile.bounds)}, source sha256 ${tile.sourceSha256}`);
