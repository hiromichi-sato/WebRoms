import { test, expect, loadSettings, readSettings } from './app-fixture.js';
import { fixture } from '../runtime-helper.mjs';

for (const width of [1280, 390]) test(`selected-side tide is inline above the section at ${width}px`, async ({ page }) => {
  test.setTimeout(30000);
  await page.setViewportSize({ width, height: 900 }); await page.goto('/');
  const config = fixture(); config.grid.geoBounds = { west: 135.1, east: 135.4, south: 34.3, north: 34.6 };
  for (const b of Object.values(config.boundary)) b.mode = 'specified';
  config.ocean = { tideMode: 'auto', startUtc: '2026-01-01T00:00:00Z', predictionDays: 45 };
  await loadSettings(page, config); await page.locator('[data-step="3"]').click();
  await page.locator('#tideEnabled').uncheck();await page.locator('#tideEnabled').check();
  await expect(page.locator('#tidePreview')).toHaveCount(0);
  await expect(page.locator('#companionColumn #boundaryTidePanel')).toContainText('西境界');
  await expect(page.locator('#boundaryForcingTools #tideScaleNumber')).toBeVisible();
  await expect(page.locator('#boundaryTidePlot polyline')).toHaveCount(1);
  await expect(page.locator('#boundaryTidePlot svg')).toHaveAttribute('data-end-hours', '720');
  await page.getByRole('button', { name: '潮汐グラフを拡大', exact: true }).click();
  await expect(page.locator('#boundaryTidePlot svg')).toHaveAttribute('data-start-hours', '180');
  await page.getByRole('button', { name: '潮汐グラフを次へ', exact: true }).click();
  await expect(page.locator('#boundaryTidePlot svg')).toHaveAttribute('data-start-hours', '360');
  await page.getByLabel('境界潮汐グラフの開始時刻', { exact: true }).evaluate(el => { el.value = '0'; el.dispatchEvent(new Event('input')); });
  const tidePlot = await page.locator('#boundaryTidePlot').boundingBox();
  await page.mouse.move(tidePlot.x + tidePlot.width * .6, tidePlot.y + tidePlot.height * .5); await page.mouse.down();
  await page.mouse.move(tidePlot.x + tidePlot.width * .4, tidePlot.y + tidePlot.height * .5, { steps: 4 }); await page.mouse.up();
  expect(Number(await page.locator('#boundaryTidePlot svg').getAttribute('data-start-hours'))).toBeGreaterThan(0);
  const heightHandle = page.locator('#boundaryHeightResizer');
  await expect(heightHandle).toBeVisible();
  const initialHeight = (await page.locator('#boundaryTidePanel').boundingBox()).height;
  await heightHandle.scrollIntoViewIfNeeded();
  const grip = await heightHandle.boundingBox();
  await page.mouse.move(grip.x + 30, grip.y + 5); await page.mouse.down();
  await page.mouse.move(grip.x + 30, grip.y + 45, { steps: 4 }); await page.mouse.up();
  expect((await page.locator('#boundaryTidePanel').boundingBox()).height).toBeGreaterThan(initialHeight + 25);
  await heightHandle.dblclick();
  const before = await page.locator('#boundaryTidePlot polyline').getAttribute('points');
  await page.locator('#tideScaleNumber').fill('1.5');
  expect(await page.locator('#boundaryTidePlot polyline').getAttribute('points')).not.toBe(before);
  await page.locator('#tideScaleNumber').press('Tab');
  await page.getByRole('button', { name: '東側の境界を設定', exact: true }).click();
  await expect(page.locator('#boundaryTidePanel')).toContainText('東境界');
  await expect(page.locator('#tideScaleNumber')).toHaveValue('1');
  await page.locator('#boundaryVariable').selectOption('salt');
  await expect(page.locator('#boundaryTidePlot svg')).toBeVisible();
  await expect(page.locator('#showBoundaryTide')).toHaveCount(0);
  await expect(page.locator('#boundaryTidePlot')).toBeVisible();
  await page.locator('#advancedTideSettings > summary').click();
  await expect(page.locator('#harmonicCell')).toHaveValue('mean');
  await page.locator('#harmonicAmpM2').fill('25'); await page.locator('#harmonicLagM2').fill('90');
  await page.locator('#applyHarmonics').click();
  await page.locator('#advancedTideSettings > summary').click();
  expect(Number(await page.locator('#harmonicAmpM2').inputValue())).toBeCloseTo(25, 8);
  expect(Number(await page.locator('#harmonicLagM2').inputValue())).toBeCloseTo(90, 8);
  await expect(page.locator('dialog[open]')).toHaveCount(0);
  const graph = await page.locator('#boundaryTidePlot').boundingBox(), section = await page.locator('.secondary-scene').boundingBox();
  const panel=await page.locator('#boundaryTidePanel').boundingBox();
  // The plot can scroll within the panel; its visible frame must not overlap the section.
  expect(panel.y + panel.height).toBeLessThan(section.y);
  expect(graph.height).toBeGreaterThan(95);
  await page.locator('#boundaryTidePanel').scrollIntoViewIfNeeded(); await page.screenshot({ path: `test-results/tide-section-${width}.png` });
  const saved = await readSettings(page);
  expect(saved.ocean.tides.points.some(p => p.amplitudeScale === 1.5)).toBeTruthy();
  await page.locator('[data-step="6"]').click(); await expect(page.locator('#boundaryTidePanel')).toHaveCount(0);
});
