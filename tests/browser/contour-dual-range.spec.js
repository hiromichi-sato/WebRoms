import { test, expect } from './app-fixture.js';

for (const width of [1280, 390]) test(`shared dual range slider and exact input at ${width}px`, async ({ page }) => {
  await page.setViewportSize({ width, height: 844 });
  await page.route('**/range-harness', route => route.fulfill({ contentType: 'text/html', body: '<!doctype html><meta charset="utf-8"><link rel="stylesheet" href="/workflow.css"><main style="padding:24px"><div id="anchor"></div></main>' }));
  await page.goto('/range-harness');
  await page.evaluate(async () => {
    const { ContourControls } = await import('/src/contour-settings.js');
    const view = { min: 0, max: 10, dataMin: 0, dataMax: 10, label: '水温 / ℃', palette: () => ['#00aabb', '#ffcc00'] };
    const refresh = () => { const c = control.get('temp'); if (!c.auto) { view.min = c.min; view.max = c.max; } control.update('temp', view, true); };
    const control = new ContourControls(document.querySelector('#anchor'), refresh);
    window.rangeControl = control; refresh();
  });
  await page.locator('#contourToggle').click();
  const low = page.locator('#contourMin'), high = page.locator('#contourMax');
  const a = await low.boundingBox(), b = await high.boundingBox();
  expect(a.y).toBe(b.y); expect(a.width).toBe(b.width);
  const domainSpan = () => page.evaluate(() => rangeControl.current.domain.max - rangeControl.current.domain.min);
  const initialSpan = await domainSpan();
  await page.getByRole('button', { name: '範囲スライダーを拡大', exact: true }).click();
  expect(await domainSpan()).toBeLessThan(initialSpan);
  expect(Number(await low.inputValue())).toBe(0); expect(Number(await high.inputValue())).toBe(10);
  await page.getByRole('button', { name: '範囲スライダーを縮小', exact: true }).click();
  const expandedSpan = await domainSpan();
  expect(expandedSpan).toBeGreaterThan(initialSpan);
  await page.locator('.contour-range').hover(); await page.mouse.wheel(0,-100);
  await expect.poll(domainSpan).toBeLessThan(expandedSpan);
  expect(Number(await low.inputValue())).toBe(0); expect(Number(await high.inputValue())).toBe(10);
  await page.locator('#contourMinNumber').fill('-200.125');
  await page.locator('#contourMinNumber').press('Tab');
  expect(await page.evaluate(() => rangeControl.current.min)).toBe(-200.125);
  await page.locator('#contourMaxNumber').fill('30.875');
  await page.locator('#contourMaxNumber').press('Tab');
  expect(await page.evaluate(() => rangeControl.current.max)).toBe(30.875);
  await expect(page.locator('#contourAuto')).not.toBeChecked();
  expect(Number(await low.inputValue())).toBe(-200.125);
  expect(Number(await high.inputValue())).toBe(30.875);
  await low.press('Home'); await high.press('End');
  expect(Number(await low.inputValue())).toBeLessThan(Number(await high.inputValue()));
  const track = page.locator('.contour-range-track'), rect = await track.boundingBox();
  await page.mouse.move(rect.x + rect.width * .3, rect.y + 4); await page.mouse.down();
  await page.mouse.move(rect.x + rect.width * .4, rect.y + 4, { steps: 5 }); await page.mouse.up();
  expect(Number(await low.inputValue())).toBeCloseTo(Number(await low.getAttribute('min')) + .4 * (Number(await low.getAttribute('max')) - Number(await low.getAttribute('min'))), 3);
  const before = await page.evaluate(() => rangeControl.current.min);
  await page.locator('#contourMinNumber').fill('99999'); await page.locator('#contourMinNumber').press('Tab');
  expect(await page.evaluate(() => rangeControl.current.min)).toBe(before);
  expect(await page.locator('#contourMinNumber').evaluate(el => el.checkValidity())).toBe(false);
  await page.locator('#contourMinNumber').fill('-10'); await page.locator('#contourMinNumber').press('Tab');
  await page.screenshot({ path: `test-results/contour-range-${width}.png` });
  const panel = await page.locator('#contourPanel').boundingBox();
  expect(panel.x).toBeGreaterThanOrEqual(0); expect(panel.x + panel.width).toBeLessThanOrEqual(width);
});
