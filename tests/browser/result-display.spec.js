import { test, expect, loadSettings, readSettings } from './app-fixture.js';
import { readFile } from 'node:fs/promises';
import { unzipSync, strFromU8 } from '../../vendor/fflate.js';
import { defaults } from '../../src/model.js';

test('result colors share manual limits and requested export runs continue after completion', async ({ page }) => {
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  const config = defaults();
  Object.assign(config.grid, { nx: 8, ny: 8, preset: 'open', minDepth: 40, maxDepth: 100 });
  Object.assign(config.numerics, { dt: 1, maxSteps: 10, steadyWindow: 10, outputInterval: 2 });
  await page.goto('/');
  await loadSettings(page, config);
  await expect(page.locator('#contourControls')).toBeHidden();
  await page.locator('.steps [data-step="6"]').click();
  await expect(page.locator('#contourPanel')).toBeHidden();
  await expect(page.locator('.view-toolbar #contourToggle')).toBeVisible();
  expect((await page.locator('#contourPreview').boundingBox()).width).toBeGreaterThan(80);
  await page.locator('#calculateButton').click();
  await expect(page.locator('#runLog')).toContainText('ROMS: DONE');
  await page.locator('#contourToggle').click();
  await expect(page.locator('#contourPanel input[type="number"]')).toHaveCount(0);
  const minSlider = page.locator('#contourMin'), maxSlider = page.locator('#contourMax');
  await minSlider.press('Home');
  await maxSlider.press('End');
  await expect(page.locator('#contourAuto')).not.toBeChecked();
  const maxValue = await maxSlider.inputValue();
  await expect(page.locator('#legendMax')).toHaveText(Number(maxValue).toPrecision(3));
  const primary = page.locator('#threeView canvas'), section = page.locator('#sectionCanvas');
  const before = await primary.evaluate(c => c.toDataURL()), beforeSection = await section.evaluate(c => c.toDataURL());
  await page.locator('[data-palette="gray"]').click();
  expect(await primary.evaluate(c => c.toDataURL())).not.toBe(before);
  expect(await section.evaluate(c => c.toDataURL())).not.toBe(beforeSection);
  await page.locator('#contourReverse').check();
  const gradient = await page.locator('#legendGradient').evaluate(e => e.style.background);
  expect(gradient).toContain('17, 17, 17');
  await minSlider.press('End');
  expect(Number(await minSlider.inputValue())).toBeLessThan(Number(await maxSlider.inputValue()));
  await minSlider.press('Home');
  await maxSlider.press('Home');
  expect(Number(await minSlider.inputValue())).toBeLessThan(Number(await maxSlider.inputValue()));
  await maxSlider.press('End');
  await page.locator('#contourExpand').click();
  expect(Number(await maxSlider.getAttribute('max'))).toBeGreaterThan(Number(maxValue));
  await page.keyboard.press('Escape');
  await expect(page.locator('#contourPanel')).toBeHidden();
  await expect(page.locator('#contourToggle')).toBeFocused();
  const preserved = await maxSlider.inputValue();
  await page.locator('#fieldSelect').selectOption('salt'); await expect(page.locator('#contourAuto')).toBeChecked();
  await page.locator('#fieldSelect').selectOption('temp'); await expect(maxSlider).toHaveValue(preserved);
  await page.locator('#contourToggle').click();
  await page.screenshot({ path: 'test-results/result-colors-desktop.png', fullPage: true });
  await page.locator('#resultButton').click();
  await expect(page.locator('#exportStart')).toHaveCount(0);
  await page.locator('#exportInterval').fill('2');
  await page.locator('#exportHours').fill('0.001');
  await expect(page.locator('#exportSummary')).toContainText('3時刻');
  await page.locator('#exportFormat').selectOption('shape');
  const download = page.waitForEvent('download'); await page.locator('#downloadResults').click();
  const files = unzipSync(await readFile(await (await download).path()));
  expect(JSON.parse(strFromU8(files['metadata.json'])).timesSeconds).toEqual([10, 12, 14]);
  await page.locator('#exportDurationPreset').selectOption('0');
  await expect(page.locator('#exportSummary')).toContainText('終了場のみ');
  await page.locator('#exportFormat').selectOption('netcdf');
  const nc = page.waitForEvent('download'); await page.locator('#downloadResults').click();
  expect((await readFile(await (await nc).path())).subarray(0, 3).toString()).toBe('CDF');
  await page.locator('#exportHours').fill('-1'); await expect(page.locator('#downloadResults')).toBeDisabled();
  await page.locator('#exportDurationPreset').selectOption('0'); await expect(page.locator('#exportSummary')).toContainText('追加RUNなし');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'test-results/result-save-mobile.png', fullPage: true });
  await page.locator('#closeResults').click();
  await page.locator('#contourControls').scrollIntoViewIfNeeded();
  await page.locator('#contourToggle').click();
  const sliderBox = await minSlider.boundingBox();
  await minSlider.click({ position: { x: sliderBox.width * .3, y: sliderBox.height / 2 } });
  await page.locator('#contourAuto').check();
  await expect(page.locator('#contourAuto')).toBeChecked();
  const panel = await page.locator('#contourPanel').boundingBox();
  expect(panel.x).toBeGreaterThanOrEqual(0); expect(panel.x + panel.width).toBeLessThanOrEqual(390);
  expect(panel.y).toBeGreaterThanOrEqual(0); expect(panel.y + panel.height).toBeLessThanOrEqual(844);
  await page.screenshot({ path: 'test-results/result-colors-mobile.png', fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect(errors).toEqual([]);
});
