import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import { unzipSync, strFromU8 } from '../../vendor/fflate.js';
import { defaults } from '../../src/model.js';

test('result colors share manual limits and final-hour exports include completion', async ({ page }) => {
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  const config = defaults();
  Object.assign(config.grid, { nx: 8, ny: 8, preset: 'open', minDepth: 40, maxDepth: 100 });
  Object.assign(config.numerics, { dt: 1, maxSteps: 10, steadyWindow: 10, outputInterval: 2 });
  await page.goto('/');
  await page.evaluate(c => localStorage.setItem('webroms.project.v1', JSON.stringify(c)), config); await page.reload();
  await expect(page.locator('#contourControls')).toBeHidden();
  await page.locator('.steps [data-step="6"]').click();
  await expect(page.locator('#contourMin')).toBeDisabled();
  await page.locator('#calculateButton').click();
  await expect(page.locator('#runLog')).toContainText('ROMS: DONE');
  await page.locator('#contourAuto').uncheck();
  await page.locator('#contourMin').fill('0'); await page.locator('#contourMin').blur();
  await page.locator('#contourMax').fill('30'); await page.locator('#contourMax').blur();
  await expect(page.locator('#legendMax')).toHaveText('30.0');
  const primary = page.locator('#threeView canvas'), section = page.locator('#sectionCanvas');
  const before = await primary.evaluate(c => c.toDataURL()), beforeSection = await section.evaluate(c => c.toDataURL());
  await page.locator('[data-palette="gray"]').click();
  expect(await primary.evaluate(c => c.toDataURL())).not.toBe(before);
  expect(await section.evaluate(c => c.toDataURL())).not.toBe(beforeSection);
  await page.locator('#contourReverse').check();
  const gradient = await page.locator('#legendGradient').evaluate(e => e.style.background);
  expect(gradient).toContain('17, 17, 17');
  await page.locator('#contourMax').fill('-1'); await page.locator('#contourMax').blur();
  await expect(page.locator('#contourError')).not.toBeEmpty();
  await expect(page.locator('#legendMax')).toHaveText('30.0');
  await page.locator('#contourMax').fill('30'); await page.locator('#contourMax').blur();
  await page.locator('#fieldSelect').selectOption('salt'); await expect(page.locator('#contourAuto')).toBeChecked();
  await page.locator('#fieldSelect').selectOption('temp'); await expect(page.locator('#contourMax')).toHaveValue('30');
  await page.screenshot({ path: 'test-results/result-colors-desktop.png', fullPage: true });
  await page.locator('#resultButton').click();
  await expect(page.locator('#exportStart')).toHaveCount(0);
  await page.locator('#exportHours').fill('0.001');
  await expect(page.locator('#exportSummary')).toContainText('2時刻');
  await page.locator('#exportFormat').selectOption('shape');
  const download = page.waitForEvent('download'); await page.locator('#downloadResults').click();
  const files = unzipSync(await readFile(await (await download).path()));
  expect(JSON.parse(strFromU8(files['metadata.json'])).timesSeconds).toEqual([8, 10]);
  await page.locator('#exportDurationPreset').selectOption('0');
  await expect(page.locator('#exportSummary')).toContainText('終了場のみ');
  await page.locator('#exportFormat').selectOption('netcdf');
  const nc = page.waitForEvent('download'); await page.locator('#downloadResults').click();
  expect((await readFile(await (await nc).path())).subarray(0, 3).toString()).toBe('CDF');
  await page.locator('#exportHours').fill('-1'); await expect(page.locator('#downloadResults')).toBeDisabled();
  await page.locator('#exportDurationPreset').selectOption('24'); await expect(page.locator('#exportSummary')).toContainText('計算期間全体');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'test-results/result-save-mobile.png', fullPage: true });
  await page.locator('#closeResults').click();
  await page.locator('#contourControls').scrollIntoViewIfNeeded();
  await page.screenshot({ path: 'test-results/result-colors-mobile.png', fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect(errors).toEqual([]);
});
